"""Compare installed devices with the complete output of their current source."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from .amxd import device_to_patcher
from .freeze import _patcher_dict_from_payload, _read_amxd, extract_frozen_amxd


def _without_timestamps(value):
    if isinstance(value, dict):
        return {key: _without_timestamps(item) for key, item in value.items()
                if key not in {"creationdate", "modificationdate"}}
    if isinstance(value, list):
        return [_without_timestamps(item) for item in value]
    return value


def _canonical_json(value) -> bytes:
    return json.dumps(_without_timestamps(value), sort_keys=True,
                      separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def _fingerprint(patcher, assets) -> str:
    records = {"patcher": hashlib.sha256(_canonical_json(patcher)).hexdigest()}
    for name, data in assets.items():
        if Path(name).suffix in {".gendsp", ".maxpat", ".json"}:
            data = _canonical_json(json.loads(data))
        records[name] = hashlib.sha256(data).hexdigest()
    return hashlib.sha256(_canonical_json(records)).hexdigest()


def device_fingerprint(device) -> str:
    """Fingerprint patcher and every asset generated by the current source.

    Executing the factory includes split modules and framework changes, while
    ignoring edits that do not affect the deliverable, such as Python comments.
    """
    assets = {a.filename: a.content if isinstance(a.content, bytes)
              else a.content.encode(a.encoding) for a in device.assets()}
    return _fingerprint(device_to_patcher(device), assets)


def file_fingerprint(path) -> str:
    """Fingerprint an installed frozen or unfrozen device; missing assets fail."""
    path = Path(path)
    _, payload, frozen = _read_amxd(str(path))
    bundled = extract_frozen_amxd(path.read_bytes()) if frozen else {}
    if frozen:
        payload = next(iter(bundled.values()))
    patcher = _patcher_dict_from_payload(payload)
    assets = {}
    for dependency in patcher.get("patcher", {}).get("dependency_cache", []):
        name = dependency.get("name")
        if name:
            assets[name] = bundled[name] if frozen else (path.parent / name).read_bytes()
    return _fingerprint(patcher, assets)
